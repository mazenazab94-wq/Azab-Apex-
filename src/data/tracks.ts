// Helper to scale an organic closed loop cleanly without self-intersection
function makeLoop(
  points: [number, number, number][],
  scaleXZ = 1,
  scaleY = 1
): [number, number, number][] {
  return points.map(([x, y, z]) => [x * scaleXZ, y * scaleY, z * scaleXZ]);
}

